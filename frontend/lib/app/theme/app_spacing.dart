/// Spacing and size constants, so screens line up.
abstract final class AppSpacing {
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
  static const double xxl = 32;

  /// Side padding of every screen.
  static const double screenPadding = 16;

  /// Corner radius of cards, buttons and fields.
  static const double radius = 14;

  /// Minimum height of a tappable button (comfortable on a pitch side, with a thumb).
  static const double buttonHeight = 52;

  /// Widest a form or card column gets on a tablet.
  static const double maxContentWidth = 560;
}
